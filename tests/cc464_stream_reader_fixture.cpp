#include "bsp/vfs_whole_stream_reader.hpp"
#include "bsp/memory_stream.hpp"

#include <cstdio>
#include <stdexcept>
#include <string>

namespace {
void require(bool value) {
    if (!value) throw std::runtime_error("chain464 stream fixture failed");
}

void check_real_memory_backing() {
    // One input crosses the transport buffer boundary and contains NULs on
    // both sides. Short native reads are valid while progress is nonzero.
    std::string source(4099, 'q');
    source[0] = source[4095] = source[4096] = '\0';
    source.back() = static_cast<char>(0xff);
    auto stream = bsp::memory_stream_from_complete_bytes(source.data(), source.size());
    std::size_t calls = 0;
    bsp::game::VfsWholeStreamReader reader(static_cast<std::uint32_t>(source.size()),
        [&](void* out, std::uint32_t requested, std::uint32_t* actual) {
            ++calls;
            // Exercise refill after a successful short read, using the same
            // real MemoryStream cursor throughout (no generated byte values).
            require(stream.read_00bef590(out, calls == 2 ? 1u : requested, actual));
        });
    const auto result = bsp::cc13_files::read_stream_to_end_00be4770(reader);
    require(result == source && calls == 3);
    require(reader.tell() == static_cast<std::int64_t>(source.size()));
    require(stream.position_00bef580() == static_cast<std::int64_t>(source.size()));

    // An opened empty extent performs no source read, as read_all did before.
    bsp::game::VfsWholeStreamReader empty(0,
        [&](void*, std::uint32_t, std::uint32_t*) { require(false); });
    require(bsp::cc13_files::read_stream_to_end_00be4770(empty).empty());

    // A real source shorter than its captured extent must still fail rather
    // than turn a partial file into a successful application result.
    auto short_stream = bsp::memory_stream_from_complete_bytes(source.data(), source.size());
    bsp::game::VfsWholeStreamReader short_reader(static_cast<std::uint32_t>(source.size() + 1),
        [&](void* out, std::uint32_t requested, std::uint32_t* actual) {
            require(short_stream.read_00bef590(out, requested, actual));
        });
    bool rejected = false;
    try { (void)bsp::cc13_files::read_stream_to_end_00be4770(short_reader); }
    catch (const std::runtime_error&) { rejected = true; }
    require(rejected);
}
}

int main() {
    try {
        check_real_memory_backing();
        std::puts("chain464 VFS stream reader fixture passed");
        return 0;
    } catch (const std::exception& error) {
        std::fprintf(stderr, "%s\n", error.what());
        return 1;
    }
}
